#!/usr/bin/env node
// Checks section 6's Species Songs (gen_tracks.mjs) against the Cairo composer of the same checkout, byte for byte.
//
//   BEAST_SONGS=<midi_fun_contract checkout of Casey's branch> node tools/species_songs_check.mjs cairo > $BEAST_SONGS/beasts/beast_contracts/src/species_songs_check.cairo
//   echo '#[cfg(test)] mod species_songs_check;' >> $BEAST_SONGS/beasts/beast_contracts/src/lib.cairo     # in a scratch worktree
//   (cd $BEAST_SONGS/beasts/beast_contracts && snforge test --max-n-steps 4294967295 --max-threads 4 species_songs_check --include-ignored > /tmp/songs.txt)
//   BEAST_SONGS=<the same checkout> node tools/species_songs_check.mjs compare /tmp/songs.txt
//
// The generated tests do what the Originals Sound Manager does for each species: get_generation_inputs({ composition_seed: 0 }, 0,
// { species_id: genesis_swap(id), name_variant_id: 0, tier, family }), then BeastPureComposer's compose_sound(Song(base_song), 0),
// and print the MIDI in hex and a hash of the settings' Cairo Serde. `compare` requires every species' MIDI to equal lab.js's
// genesisMidi(id, false) and its settings to hash to synth_settings.mjs's family settings (the Yeti's for species 68), which are what
// gen_tracks.mjs puts on the page. Needs scarb and snforge as the checkout's .tool-versions pins them. Run the snforge test in a
// scratch worktree: it edits lib.cairo, and the hex is large.
import fs from "node:fs";

const mode = process.argv[2];
const dir = process.env.BEAST_SONGS || (console.error("set BEAST_SONGS"), process.exit(2));
const bs = dir + "/offchain/beast-sound";

if (mode === "cairo") {
  const tests = Array.from({ length: 25 }, (_, b) => `#[test]\n#[ignore]\nfn species_songs_check_${String(b).padStart(2, "0")}() {\n${[1, 2, 3].map((k) => `    one(${b * 3 + k});\n`).join("")}}\n`);
  process.stdout.write(`//! Generated by beast-sound-check's tools/species_songs_check.mjs: the Sound Manager's Original path for every species, run through the
//! contract's own functions.
use beast_composer::composition::generation::get_generation_inputs;
use beast_composer::composition::genesis::{genesis_swap, species_tier, species_type};
use beast_composer::inputs::{BeastMusicalIdentity, ComposerInputs, EditionCompositionConfig};
use crate::pure_composer::compose_sound;

fn hexof(bytes: @ByteArray) -> ByteArray {
    let mut hex: ByteArray = "";
    let mut i = 0;
    while i < bytes.len() {
        let x = bytes.at(i).unwrap();
        let (hi, lo) = DivRem::div_rem(x, 16);
        hex.append_byte(if hi < 10 { 48 + hi } else { 87 + hi });
        hex.append_byte(if lo < 10 { 48 + lo } else { 87 + lo });
        i += 1;
    }
    hex
}

fn one(id: u64) {
    let sw = genesis_swap(id);
    let identity = BeastMusicalIdentity {
        species_id: sw.try_into().unwrap(), name_variant_id: 0, tier: species_tier(sw), family: species_type(sw),
    };
    let base = get_generation_inputs(EditionCompositionConfig { composition_seed: 0 }, 0, identity);
    let sound = compose_sound(ComposerInputs::Song(base.base_song), 0);
    let mut out: Array<felt252> = array![];
    Serde::serialize(@sound.settings, ref out);
    println!(
        "SP id={} len={} shash={} hex={}", id, sound.midi.len(), core::poseidon::poseidon_hash_span(out.span()),
        hexof(@sound.midi),
    );
}

${tests.join("\n")}`);
} else if (mode === "compare") {
  const idx = await import(bs + "/src/index.js"), v11 = await import(bs + "/src/engine_v11.js"), lab = await import(bs + "/src/lab.js");
  const SS = await import(bs + "/onchain/tinychip/synth_settings.mjs");
  const E = idx.engine, V = v11.createEngineV11(E);
  const lines = fs.readFileSync(process.argv[3], "latin1").split("\n").filter((l) => l.startsWith("SP "));
  const bad = [];
  for (const l of lines) {
    const kv = Object.fromEntries(l.trim().split(/\s+/).slice(1).map((x) => x.split("=")));
    const id = +kv.id, swap = lab.GENESIS_SWAPS[id] || id;
    const midi = Buffer.from(lab.genesisMidi(id, false, E, V).midi);
    const settings = SS.beastSynthSettings(undefined, SS.variantPrograms({ type: lab.speciesType(swap), mega: false, yeti: swap === 68 }));
    const sameMidi = midi.length === +kv.len && midi.toString("hex") === kv.hex, sameSettings = idx.poseidonHashMany(SS.serializeSettings(settings)).toString() === kv.shash;
    if (!sameMidi || !sameSettings) bad.push(`${id}: midi ${sameMidi}, settings ${sameSettings}`);
  }
  console.log(`${lines.length} species: ${lines.length - bad.length} identical to the Cairo composer${bad.length ? "\n" + bad.join("\n") : ""}`);
  process.exit(lines.length === 75 && !bad.length ? 0 : 1);
} else {
  console.error("usage: species_songs_check.mjs cairo | compare <snforge output>");
  process.exit(2);
}
